export const HOLIDAY_YEARS = [2026, 2027] as const;

/** 공휴일 이름. 표에 없으면 null(토 · 일도 null). */
export function holidayName(date: string): string | null {
  return TABLE[date] ?? null;
}

/** 휴일 표의 날 전부. 검사용. */
export function holidayDates(): string[] {
  return Object.keys(TABLE).sort();
}

/** 이 날이 휴일근무인가. 토 · 일이거나 표의 공휴일. */
export function isHoliday(date: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) return false;
  const day = new Date(`${date}T12:00:00+09:00`).getUTCDay();
  return day === 0 || day === 6 || date in TABLE;
}

/** 화면에 붙일 이름. 「휴일 · 추석」, 「휴일 · 토요일」, 평일이면 null. */
export function holidayLabel(date: string): string | null {
  const name = holidayName(date);
  if (name) return name;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) return null;
  const day = new Date(`${date}T12:00:00+09:00`).getUTCDay();
  return day === 0 ? "일요일" : day === 6 ? "토요일" : null;
}
